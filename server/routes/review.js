// review.js – Proposal Review Assistant
const express = require('express');
const router = express.Router();
const { requireAuth, requireRole } = require('../middleware/auth');

// Placeholder LLM call – replace with real LLM SDK/API
async function generateReview(text) {
  // In production, call your LLM provider here.
  // For now, return a canned response.
  return `Review for the proposal: \n\n${text.slice(0, 200)}...\n\n[Review generated by placeholder AI]`;
}

// Guide or Coordinator can request a review of a proposal
router.post('/proposal', requireAuth, requireRole('guide'), async (req, res) => {
  const { proposal } = req.body;
  if (!proposal || typeof proposal !== 'string') {
    return res.status(400).json({ error: 'proposal text is required' });
  }
  try {
    const review = await generateReview(proposal);
    res.json({ review });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'LLM service error' });
  }
});

module.exports = router;
